#!/usr/bin/env node
// Refresh the reviewable built-in fallback for non-standard Secret Lair
// catalogs. Runtime refreshes use the same transformer and keep a newer local
// cache, but shipping a seed makes these views useful immediately after update.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'src', 'renderer-js', 'data', 'slSupplementalSeed.js');
const headers = { 'User-Agent': 'ManaLedgerCatalogBuilder/1.0', Accept: 'application/json' };

async function scryfall(query) {
  let url = `https://api.scryfall.com/cards/search?q=${encodeURIComponent(query)}&order=set&unique=prints`;
  const cards = [];
  while (url) {
    const resp = await fetch(url, { headers });
    if (!resp.ok) throw new Error(`Scryfall ${resp.status}: ${query}`);
    const json = await resp.json();
    cards.push(...(json.data || []));
    url = json.has_more ? json.next_page : null;
  }
  return cards;
}

(async () => {
  const { buildSlSupplementalCatalog, SL_RECENT_SLD_QUERY } = await import('../src/renderer-js/slSupplemental.js');
  const [slp, pssc, slx, ptg, slc, slu, slz, recentSld, serialized, mtgResp] = await Promise.all([
    scryfall('set:slp'), scryfall('set:pssc'), scryfall('set:slx'), scryfall('set:ptg'),
    scryfall('set:slc'), scryfall('set:slu'), scryfall('set:slz'),
    scryfall(SL_RECENT_SLD_QUERY), scryfall('set:sld is:serialized'), fetch('https://mtgjson.com/api/v5/SLD.json', { headers }),
  ]);
  if (!mtgResp.ok) throw new Error(`MTGJSON ${mtgResp.status}`);
  const mtgjson = await mtgResp.json();
  const catalog = buildSlSupplementalCatalog({ slp, pssc, slx, ptg, slc, slu, slz, 'sld-current': recentSld, 'sld-serialized': serialized }, mtgjson);
  fs.writeFileSync(OUT, '// Generated by scripts/build-sl-supplemental.js. Do not hand-edit.\nexport default '
    + JSON.stringify(catalog, null, 2) + ';\n');
  console.log(`Wrote ${path.relative(ROOT, OUT)} · ${catalog.sets.reduce((n, s) => n + s.cards.length, 0)} cards · ${catalog.bundles.length} bundles`);
})().catch(error => {
  console.error(error);
  process.exit(1);
});

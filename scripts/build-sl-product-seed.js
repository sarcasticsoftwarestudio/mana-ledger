#!/usr/bin/env node
// Build a current exact-SKU fallback from MTGJSON SLD. The live refresh uses
// the same model builder; shipping this compact model prevents newly released
// SLD products with incomplete subset tags from disappearing on a clean install.

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'src', 'renderer-js', 'data', 'slProductSeed.js');
const headers = { 'User-Agent': 'ManaLedgerProductSeed/1.0', Accept: 'application/json' };

(async () => {
  const response = await fetch('https://mtgjson.com/api/v5/SLD.json', { headers });
  if (!response.ok) throw new Error(`MTGJSON ${response.status}`);
  const json = await response.json();
  const source = fs.readFileSync(path.join(ROOT, 'src', 'renderer', 'secretlair.js'), 'utf8')
    + '\n;globalThis.__drops=Object.keys(SL_DROP_CARDS);';
  const context = {};
  vm.createContext(context);
  vm.runInContext(source, context);
  const { buildSlModel } = await import('../src/renderer-js/slData.js');
  const model = buildSlModel(json, { knownDrops: context.__drops || [] });
  const seed = { generatedAt: new Date().toISOString(), products: model.products, scryfallToName: model.scryfallToName };
  fs.writeFileSync(OUT, '// Generated by scripts/build-sl-product-seed.js. Do not hand-edit.\nexport default '
    + JSON.stringify(seed, null, 2) + ';\n');
  console.log(`Wrote ${path.relative(ROOT, OUT)} · ${model.products.length} products · ${Object.keys(model.scryfallToName).length} printings`);
})().catch(error => {
  console.error(error);
  process.exit(1);
});
